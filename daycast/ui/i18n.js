const LANGUAGES = [
  { id: "en", name: "English", locale: "en-GB" },
  { id: "it", name: "Italiano", locale: "it-IT" },
];

let currentLang = "en";

function t(key, vars = {}) {
  const text = STRINGS[currentLang]?.[key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}

function locale() {
  return LANGUAGES.find((l) => l.id === currentLang)?.locale ?? "en-GB";
}

function setLanguage(lang) {
  currentLang = STRINGS[lang] ? lang : "en";
  document.documentElement.lang = currentLang;
  // testi fissi dell'HTML: data-i18n (testo), data-i18n-title, -aria, -placeholder
  for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll("[data-i18n-title]")) node.title = t(node.dataset.i18nTitle);
  for (const node of document.querySelectorAll("[data-i18n-aria]")) node.setAttribute("aria-label", t(node.dataset.i18nAria));
  for (const node of document.querySelectorAll("[data-i18n-placeholder]")) node.placeholder = t(node.dataset.i18nPlaceholder);
}
